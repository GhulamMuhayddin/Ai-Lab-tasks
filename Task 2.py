values = [12, 24, 36, 48, 60, 72]
print("List:", values)

# Indexing
print("First value:", values[0])
print("Third value:", values[2])
print("Last value:", values[-1])

# Slicing
print("First three values:", values[:3])
print("Values from index 2 to 4:", values[2:5])
print("Last three values:", values[-3:])
